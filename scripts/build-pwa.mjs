import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
let commit =
  process.env.VERCEL_GIT_COMMIT_SHA || process.env.EDUPLAN_SOURCE_SHA;
if (!commit)
  try {
    commit = execFileSync("git", ["rev-parse", "--short", "HEAD"], {
      encoding: "utf8",
    }).trim();
  } catch {
    commit = "local";
  }
writeFileSync(
  "public/lesson-sw.js",
  `// Generated by scripts/build-pwa.mjs.\nconst RELEASE=${JSON.stringify(commit)};\n` +
    readFileSync("src/service-worker.js", "utf8"),
);
