import {test,expect} from "@playwright/test";
import {Workbook} from "exceljs";

test("select and add subjects, allocate weekly hours, then produce only those rows",async({page})=>{
  await page.goto("/recovery-preview/curriculum");
  const next=page.getByRole("button",{name:"선택한 과목의 시수 입력",exact:true});
  await expect(page.getByRole("heading",{name:"이번에 편성할 과목을 선택하세요"})).toBeVisible();
  await expect(next).toBeDisabled();
  await page.getByRole("checkbox",{name:"국어 편성 과목 선택",exact:true}).check();
  await page.getByRole("checkbox",{name:"수학 편성 과목 선택",exact:true}).check();
  await expect(page.getByText("자동 저장 완료",{exact:false})).toBeVisible();
  const group=page.getByRole("region",{name:"선택 교과군",exact:true});
  await group.getByRole("button",{name:"과목 추가",exact:true}).click();
  await group.getByLabel("새 과목명",{exact:true}).fill("학교 텃밭 연구");
  await expect(next).toBeDisabled();
  await group.getByRole("button",{name:"과목 등록",exact:true}).click();
  const customChoice=page.getByRole("checkbox",{name:"학교 텃밭 연구 편성 과목 선택",exact:true});
  await expect(customChoice).not.toBeChecked();
  await customChoice.check();
  await expect(page.getByText("자동 저장 완료",{exact:false})).toBeVisible();
  await next.click();
  const korean=page.getByRole("textbox",{name:"국어 1학년 1학기 주당 시수",exact:true});
  await expect(page.getByRole("textbox",{name:"영어 1학년 1학기 주당 시수",exact:true})).toHaveCount(0);
  await korean.fill("4");await korean.press("Tab");
  const custom=page.getByRole("textbox",{name:"학교 텃밭 연구 1학년 1학기 주당 시수",exact:true});
  await custom.fill("2");await custom.press("Tab");
  await expect(page.getByText("자동 저장 완료",{exact:false})).toBeVisible();
  await page.getByRole("button",{name:"교육과정표 보기",exact:true}).click();
  const table=page.getByRole("region",{name:"교과 시수 엑셀식 편성표"});
  await expect(table.getByRole("textbox")).toHaveCount(0);
  await expect(table.getByRole("row").filter({has:page.getByRole("rowheader",{name:"국어",exact:true})})).toContainText("64");
  await expect(table.getByRole("row").filter({has:page.getByRole("rowheader",{name:"학교 텃밭 연구",exact:true})})).toContainText("32");
  await expect(page.getByText("3개년 총 96시간",{exact:true})).toBeVisible();
  const downloaded=page.waitForEvent("download");
  await page.getByRole("button",{name:"현대화 엑셀",exact:true}).click();
  const workbook=new Workbook();await workbook.xlsx.readFile((await (await downloaded).path())!);
  const names=workbook.getWorksheet("학기별 시수")!.getColumn(2).values;
  expect(names).toContain("학교 텃밭 연구");expect(names).toContain("수학");expect(names).not.toContain("영어");
  await page.reload();
  await expect(page.getByRole("checkbox",{name:"학교 텃밭 연구 편성 과목 선택",exact:true})).toBeChecked();
  await expect(page.getByRole("checkbox",{name:"국어 편성 과목 선택",exact:true})).toBeDisabled();
  await page.getByRole("checkbox",{name:"수학 편성 과목 선택",exact:true}).uncheck();
  await expect(page.getByText("자동 저장 완료",{exact:false})).toBeVisible();
  await next.click();
  await expect(korean).toHaveValue("4");await expect(custom).toHaveValue("2");
  await expect(page.getByRole("textbox",{name:"수학 1학년 1학기 주당 시수",exact:true})).toHaveCount(0);
});

test("cohort selection is isolated and unselected new plans cannot skip to hours",async({page})=>{
  await page.goto("/recovery-preview/curriculum");
  await page.getByRole("checkbox",{name:"국어 편성 과목 선택",exact:true}).check();
  await expect(page.getByText("자동 저장 완료",{exact:false})).toBeVisible();
  await page.getByRole("button",{name:"새 입학년도 선택"}).click();
  await page.getByRole("spinbutton",{name:"새 입학년도",exact:true}).fill("2028");
  await page.getByRole("button",{name:"선택",exact:true}).click();
  await page.getByRole("button",{name:"편성 시작",exact:true}).click();
  await expect(page.getByRole("checkbox",{name:"국어 편성 과목 선택",exact:true})).not.toBeChecked();
  await expect(page.getByRole("button",{name:"선택한 과목의 시수 입력",exact:true})).toBeDisabled();
  await page.getByRole("checkbox",{name:"영어 편성 과목 선택",exact:true}).check();
  await expect(page.getByText("자동 저장 완료",{exact:false})).toBeVisible();
  await page.getByLabel("입학년도",{exact:true}).selectOption("2027");
  await expect(page.getByRole("checkbox",{name:"국어 편성 과목 선택",exact:true})).toBeChecked();
  await expect(page.getByRole("checkbox",{name:"영어 편성 과목 선택",exact:true})).not.toBeChecked();
});
